//! ChatMix: two virtual outputs, "Arctis Game" and "Arctis Chat", that both
//! play into the headset. The balance — from the base station's dial or the
//! app's slider — sets the volume of each before they are mixed.
//!
//! Like the mic chain, the two loopbacks live in their own `pipewire` process
//! under `arctis-chatmix.service`, so turning ChatMix on or off does not
//! interrupt other audio.

use crate::audio::{self, Service};
use serde::{Deserialize, Serialize};
use std::sync::Mutex;
use std::time::Duration;

pub const GAME_SINK: &str = "arctis_game";
pub const CHAT_SINK: &str = "arctis_chat";
const GAME_OUT: &str = "arctis_game.output";
const CHAT_OUT: &str = "arctis_chat.output";

pub const SERVICE: Service = Service {
    unit: "arctis-chatmix.service",
    description: "Arctis Control ChatMix game/chat outputs",
    conf_name: "chatmix.conf",
};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(default)]
pub struct ChatMixSettings {
    pub enabled: bool,
    /// -100 = all game … 0 = both full … +100 = all chat.
    pub balance: i8,
    /// Follow the base station's dial.
    pub use_dial: bool,
}

impl Default for ChatMixSettings {
    fn default() -> Self {
        Self {
            enabled: false,
            balance: 0,
            use_dial: true,
        }
    }
}

/// Volumes (0-100) for a balance, matching how the dial behaves: the centre
/// is both at full, turning one way only lowers the other side.
pub fn levels(balance: i8) -> (u8, u8) {
    let b = i16::from(balance.clamp(-100, 100));
    let game = if b <= 0 { 100 } else { 100 - b };
    let chat = if b >= 0 { 100 } else { 100 + b };
    (game as u8, chat as u8)
}

/// Inverse of `levels` for a dial report.
pub fn balance_from(game: u8, chat: u8) -> i8 {
    let (g, c) = (i16::from(game.min(100)), i16::from(chat.min(100)));
    // Chat turned down => towards game (negative); game turned down => chat.
    let b = if g >= c { c - 100 } else { 100 - g };
    b.clamp(-100, 100) as i8
}

#[derive(Debug, Serialize, Clone)]
pub struct ChatMixStatus {
    pub enabled: bool,
    pub active: bool,
    pub game: u8,
    pub chat: u8,
    pub balance: i8,
    pub default_sink: Option<String>,
    pub headset_sink: Option<String>,
}

pub fn status(s: &ChatMixSettings) -> ChatMixStatus {
    let (game, chat) = levels(s.balance);
    ChatMixStatus {
        enabled: s.enabled,
        active: audio::sink_exists(GAME_SINK) && audio::sink_exists(CHAT_SINK),
        game,
        chat,
        balance: s.balance,
        default_sink: audio::default_sink(),
        headset_sink: audio::hardware_sink(),
    }
}

fn loopback(name: &str, out: &str, label: &str, target: &Option<String>) -> String {
    let target = target
        .as_ref()
        .map(|t| format!(" target.object = \"{t}\""))
        .unwrap_or_default();
    format!(
        "  {{ name = libpipewire-module-loopback\n\
    args = {{\n\
      node.description = \"{label}\"\n\
      audio.position = [ FL FR ]\n\
      capture.props = {{ node.name = \"{name}\" node.description = \"{label}\" media.class = Audio/Sink }}\n\
      playback.props = {{ node.name = \"{out}\" node.passive = true node.dont-fallback = true stream.dont-remix = true{target} }}\n\
    }}\n\
  }}"
    )
}

pub fn render(target: &Option<String>) -> String {
    format!(
        "# Generated by Arctis Control — change settings in the app, not here.\n\
context.properties = {{ log.level = 0 }}\n\
context.spa-libs = {{\n\
  audio.convert.* = audioconvert/libspa-audioconvert\n\
  support.*       = support/libspa-support\n\
}}\n\
context.modules = [\n\
  {{ name = libpipewire-module-rt flags = [ ifexists nofail ] }}\n\
  {{ name = libpipewire-module-protocol-native }}\n\
  {{ name = libpipewire-module-client-node }}\n\
  {{ name = libpipewire-module-adapter }}\n\
{}\n\
{}\n\
]\n",
        loopback(GAME_SINK, GAME_OUT, "Arctis Game", target),
        loopback(CHAT_SINK, CHAT_OUT, "Arctis Chat", target)
    )
}

pub fn enable(s: &ChatMixSettings) -> Result<ChatMixStatus, String> {
    let target = audio::hardware_sink();
    if target.is_none() {
        return Err("headset output not found — is the base station connected?".into());
    }
    forget_ids();
    SERVICE.apply(&render(&target))?;
    if !audio::wait_for(Duration::from_secs(6), || {
        audio::sink_exists(GAME_SINK) && audio::sink_exists(CHAT_SINK)
    }) {
        return Err("ChatMix outputs did not appear — see `journalctl --user -u arctis-chatmix`".into());
    }
    apply_balance(s.balance)?;
    // Route new audio to Game by default, like GG does.
    if audio::default_sink() == audio::hardware_sink() {
        let _ = audio::set_default_sink(GAME_SINK);
    }
    Ok(status(s))
}

pub fn disable(s: &ChatMixSettings) -> Result<ChatMixStatus, String> {
    let ours = matches!(audio::default_sink().as_deref(), Some(GAME_SINK) | Some(CHAT_SINK));
    if ours {
        if let Some(hw) = audio::hardware_sink() {
            let _ = audio::set_default_sink(&hw);
        }
    }
    SERVICE.remove()?;
    forget_ids();
    Ok(status(s))
}

pub fn ensure(s: &ChatMixSettings) -> Result<(), String> {
    if s.enabled {
        enable(s).map(|_| ())
    } else {
        Ok(())
    }
}

/// Node ids of the two loopback outputs; looked up once (pw-dump is slow)
/// and refreshed when a volume change fails.
static IDS: Mutex<Option<(u32, u32)>> = Mutex::new(None);

fn lookup_ids() -> Result<(u32, u32), String> {
    let ids = audio::node_ids(&[GAME_OUT, CHAT_OUT]);
    match (ids.get(GAME_OUT), ids.get(CHAT_OUT)) {
        (Some(g), Some(c)) => Ok((*g, *c)),
        _ => Err("ChatMix is not running".into()),
    }
}

/// Sets the two loopback stream volumes.
pub fn apply_balance(balance: i8) -> Result<(), String> {
    let (game, chat) = levels(balance);
    let set = |(g, c): (u32, u32)| -> Result<(), String> {
        audio::set_node_volume(g, f32::from(game) / 100.0)?;
        audio::set_node_volume(c, f32::from(chat) / 100.0)
    };
    let cached = *IDS.lock().map_err(|_| "lock poisoned")?;
    if let Some(ids) = cached {
        if set(ids).is_ok() {
            return Ok(());
        }
    }
    let ids = lookup_ids()?;
    if let Ok(mut slot) = IDS.lock() {
        *slot = Some(ids);
    }
    set(ids)
}

fn forget_ids() {
    if let Ok(mut slot) = IDS.lock() {
        *slot = None;
    }
}

pub fn set_default(which: &str) -> Result<(), String> {
    let sink = if which == "chat" { CHAT_SINK } else { GAME_SINK };
    if !audio::sink_exists(sink) {
        return Err("ChatMix is not running".into());
    }
    audio::set_default_sink(sink)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn centre_is_both_full() {
        assert_eq!(levels(0), (100, 100));
        assert_eq!(levels(-100), (100, 0));
        assert_eq!(levels(100), (0, 100));
        assert_eq!(levels(40), (60, 100));
        assert_eq!(levels(-25), (100, 75));
    }

    #[test]
    fn dial_round_trips() {
        for b in [-100i8, -60, -1, 0, 1, 33, 100] {
            let (g, c) = levels(b);
            assert_eq!(balance_from(g, c), b, "balance {b}");
        }
    }

    #[test]
    fn config_has_two_sinks_on_the_headset() {
        let conf = render(&Some("alsa_output.hw".into()));
        assert_eq!(conf.matches("media.class = Audio/Sink").count(), 2);
        assert_eq!(conf.matches("target.object = \"alsa_output.hw\"").count(), 2);
        assert!(conf.contains("\"arctis_game\"") && conf.contains("\"arctis_chat\""));
    }
}
