//! PipeWire plumbing shared by the microphone chain and ChatMix.
//!
//! Each feature runs as its *own* `pipewire -c <conf>` process under a
//! `systemd --user` unit tied to `pipewire.service`. Turning a feature on or
//! off, or rebuilding its graph, therefore restarts only that small process —
//! the rest of the desktop's audio never drops out. Parameter changes go to
//! the running graph with `pw-cli set-param … Props { params = [...] }`.

use std::collections::HashMap;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::time::{Duration, Instant};

pub fn config_home() -> PathBuf {
    xdg("XDG_CONFIG_HOME", ".config")
}

pub fn data_home() -> PathBuf {
    xdg("XDG_DATA_HOME", ".local/share")
}

fn xdg(var: &str, fallback: &str) -> PathBuf {
    std::env::var_os(var)
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(fallback)))
        .unwrap_or_else(|| PathBuf::from("."))
}

pub fn app_config_dir() -> PathBuf {
    config_home().join("arctis-control")
}

fn which(cmd: &str) -> Option<PathBuf> {
    std::env::var_os("PATH").and_then(|paths| {
        std::env::split_paths(&paths)
            .map(|dir| dir.join(cmd))
            .find(|p| p.is_file())
    })
}

pub fn run(cmd: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(cmd)
        .args(args)
        .stdin(Stdio::null())
        .output()
        .map_err(|e| format!("{cmd}: {e}"))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        let err = String::from_utf8_lossy(&out.stderr).trim().to_string();
        Err(if err.is_empty() {
            format!("{cmd} {} failed", args.join(" "))
        } else {
            err
        })
    }
}

/// Writes `path` only when the content differs; returns whether it changed.
pub fn write_if_changed(path: &Path, body: &str) -> Result<bool, String> {
    if std::fs::read_to_string(path).map(|old| old == body).unwrap_or(false) {
        return Ok(false);
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, body).map_err(|e| format!("write {}: {e}", tmp.display()))?;
    std::fs::rename(&tmp, path).map_err(|e| format!("write {}: {e}", path.display()))?;
    Ok(true)
}

// ------------------------------------------------------ user services ---

/// A `pipewire -c <conf>` process managed by systemd --user.
pub struct Service {
    pub unit: &'static str,
    pub description: &'static str,
    pub conf_name: &'static str,
}

impl Service {
    pub fn conf_path(&self) -> PathBuf {
        app_config_dir().join(self.conf_name)
    }

    fn unit_path(&self) -> PathBuf {
        config_home().join("systemd/user").join(self.unit)
    }

    fn unit_body(&self) -> Result<String, String> {
        let pipewire = which("pipewire").ok_or("pipewire binary not found in PATH")?;
        Ok(format!(
            "# Generated by Arctis Control.\n\
[Unit]\n\
Description={}\n\
After=pipewire.service\n\
PartOf=pipewire.service\n\
\n\
[Service]\n\
ExecStart=\"{}\" -c \"{}\"\n\
Restart=on-failure\n\
RestartSec=2\n\
\n\
[Install]\n\
WantedBy=pipewire.service\n",
            self.description,
            pipewire.display(),
            self.conf_path().display()
        ))
    }

    pub fn is_installed(&self) -> bool {
        self.unit_path().exists()
    }

    pub fn is_active(&self) -> bool {
        Command::new("systemctl")
            .args(["--user", "is-active", "--quiet", self.unit])
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    }

    /// Writes the config and unit, enables the unit, and (re)starts it when
    /// anything changed or it is not running.
    pub fn apply(&self, conf: &str) -> Result<(), String> {
        let conf_changed = write_if_changed(&self.conf_path(), conf)?;
        let unit_changed = write_if_changed(&self.unit_path(), &self.unit_body()?)?;
        if unit_changed {
            run("systemctl", &["--user", "daemon-reload"])?;
        }
        run("systemctl", &["--user", "enable", self.unit])?;
        if conf_changed || unit_changed || !self.is_active() {
            run("systemctl", &["--user", "restart", self.unit])?;
        }
        Ok(())
    }

    pub fn restart(&self) -> Result<(), String> {
        run("systemctl", &["--user", "restart", self.unit]).map(|_| ())
    }

    pub fn remove(&self) -> Result<(), String> {
        if self.is_installed() {
            let _ = run("systemctl", &["--user", "disable", "--now", self.unit]);
            let _ = std::fs::remove_file(self.unit_path());
            let _ = run("systemctl", &["--user", "daemon-reload"]);
        }
        let _ = std::fs::remove_file(self.conf_path());
        Ok(())
    }
}

// ------------------------------------------------------------- nodes ---

/// `pactl list short <kind>` rows as (name, state).
fn pactl_short(kind: &str) -> Vec<(String, String)> {
    run("pactl", &["list", "short", kind])
        .map(|text| {
            text.lines()
                .filter_map(|l| {
                    let cols: Vec<&str> = l.split('\t').collect();
                    Some((cols.get(1)?.to_string(), cols.get(4).unwrap_or(&"").to_string()))
                })
                .collect()
        })
        .unwrap_or_default()
}

fn is_arctis(name: &str) -> bool {
    name.contains("Arctis_Nova_Pro") || name.contains("SteelSeries_Arctis")
}

/// The headset's own capture node (not a monitor, not ours).
pub fn hardware_mic() -> Option<String> {
    pactl_short("sources")
        .into_iter()
        .map(|(n, _)| n)
        .find(|n| n.starts_with("alsa_input.") && is_arctis(n))
}

/// The headset's own playback node.
pub fn hardware_sink() -> Option<String> {
    pactl_short("sinks")
        .into_iter()
        .map(|(n, _)| n)
        .find(|n| n.starts_with("alsa_output.") && is_arctis(n))
}

pub fn source_exists(name: &str) -> bool {
    pactl_short("sources").iter().any(|(n, _)| n == name)
}

pub fn sink_exists(name: &str) -> bool {
    pactl_short("sinks").iter().any(|(n, _)| n == name)
}

pub fn wait_for(deadline: Duration, mut ready: impl FnMut() -> bool) -> bool {
    let end = Instant::now() + deadline;
    while Instant::now() < end {
        if ready() {
            return true;
        }
        std::thread::sleep(Duration::from_millis(150));
    }
    ready()
}

/// PipeWire object ids by `node.name`, from one `pw-dump` snapshot.
pub fn node_ids(names: &[&str]) -> HashMap<String, u32> {
    let mut found = HashMap::new();
    let Ok(text) = run("pw-dump", &[]) else {
        return found;
    };
    let Ok(serde_json::Value::Array(objects)) = serde_json::from_str::<serde_json::Value>(&text)
    else {
        return found;
    };
    for o in objects {
        let name = o
            .pointer("/info/props/node.name")
            .and_then(|v| v.as_str())
            .unwrap_or_default();
        if names.contains(&name) {
            if let Some(id) = o.get("id").and_then(|v| v.as_u64()) {
                found.insert(name.to_string(), id as u32);
            }
        }
    }
    found
}

pub fn node_id(name: &str) -> Option<u32> {
    node_ids(&[name]).remove(name)
}

/// Live-updates filter-chain controls: `[("comp:Ratio", 4.0), ...]`.
pub fn set_filter_params(node: &str, params: &[(String, f32)]) -> Result<(), String> {
    if params.is_empty() {
        return Ok(());
    }
    let id = node_id(node).ok_or_else(|| format!("{node} is not running"))?;
    let body: Vec<String> = params
        .iter()
        .map(|(k, v)| format!("\"{k}\" {v:.4}"))
        .collect();
    let pod = format!("{{ params = [ {} ] }}", body.join(" "));
    run("pw-cli", &["set-param", &id.to_string(), "Props", &pod]).map(|_| ())
}

pub fn set_default_source(name: &str) -> Result<(), String> {
    run("pactl", &["set-default-source", name]).map(|_| ())
}

pub fn set_default_sink(name: &str) -> Result<(), String> {
    run("pactl", &["set-default-sink", name]).map(|_| ())
}

pub fn default_source() -> Option<String> {
    run("pactl", &["get-default-source"]).ok().map(|s| s.trim().to_string())
}

pub fn default_sink() -> Option<String> {
    run("pactl", &["get-default-sink"]).ok().map(|s| s.trim().to_string())
}

/// Linear 0..1 stream volume on a node by id.
pub fn set_node_volume(id: u32, volume: f32) -> Result<(), String> {
    run("wpctl", &["set-volume", &id.to_string(), &format!("{:.3}", volume.clamp(0.0, 1.0))])
        .map(|_| ())
}

// ---------------------------------------------------- child processes ---

/// A helper process (meter, monitor loopback, recorder) killed on drop.
pub struct Proc {
    child: Child,
    stop: Arc<AtomicBool>,
}

impl Drop for Proc {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

pub fn spawn(cmd: &str, args: &[String]) -> Result<Proc, String> {
    let child = Command::new(cmd)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| format!("{cmd}: {e}"))?;
    Ok(Proc {
        child,
        stop: Arc::new(AtomicBool::new(false)),
    })
}

#[derive(Debug, Clone, Copy, serde::Serialize)]
pub struct Level {
    pub peak_db: f32,
    pub rms_db: f32,
}

/// Records `target` at 16 kHz mono and calls `on_level` every 50 ms.
pub fn spawn_meter(
    target: &str,
    on_level: impl Fn(Level) + Send + 'static,
) -> Result<Proc, String> {
    // --raw: headerless native-endian samples (the default container is
    // big-endian AU).
    let mut child = Command::new("pw-record")
        .args([
            "--raw",
            "--target",
            target,
            "--rate",
            "16000",
            "--channels",
            "1",
            "--format",
            "s16",
            "--latency",
            "20ms",
            "-P",
            "{ node.name = arctis_meter node.dont-reconnect = true node.dont-fallback = true }",
            "-",
        ])
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| format!("pw-record: {e}"))?;
    let mut stdout = child.stdout.take().ok_or("pw-record: no stdout")?;
    let stop = Arc::new(AtomicBool::new(false));
    let flag = stop.clone();
    std::thread::spawn(move || {
        const WINDOW: usize = 800; // 50 ms
        let mut bytes = [0u8; WINDOW * 2];
        while !flag.load(Ordering::Relaxed) {
            if stdout.read_exact(&mut bytes).is_err() {
                break;
            }
            let mut peak = 0f32;
            let mut sum = 0f64;
            for pair in bytes.as_chunks::<2>().0 {
                let v = f32::from(i16::from_le_bytes(*pair)) / 32768.0;
                peak = peak.max(v.abs());
                sum += f64::from(v * v);
            }
            let rms = (sum / WINDOW as f64).sqrt() as f32;
            on_level(Level {
                peak_db: 20.0 * (peak + 1e-6).log10(),
                rms_db: 20.0 * (rms + 1e-6).log10(),
            });
        }
    });
    Ok(Proc { child, stop })
}

pub fn runtime_dir() -> PathBuf {
    std::env::var_os("XDG_RUNTIME_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir)
}
